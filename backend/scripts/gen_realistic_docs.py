# 中文数字（章/条编号）
_CN_NUM = "零一二三四五六七八九"


def cn(n: int) -> str:
    """1~999 → 中文数字（含百位边界：100=一百、105=一百零五、110=一百一十）"""
    if n < 10:
        return _CN_NUM[n]
    if n < 20:
        return "十" + (_CN_NUM[n % 10] if n % 10 else "")
    if n < 100:
        return _CN_NUM[n // 10] + "十" + (_CN_NUM[n % 10] if n % 10 else "")
    h, rest = n // 100, n % 100
    if rest == 0:
        return _CN_NUM[h] + "百"
    if rest < 10:
        return _CN_NUM[h] + "百零" + _CN_NUM[rest]
    if rest < 20:
        # 110=一百一十（"十"在百位余数里要带"一"）
        return _CN_NUM[h] + "百一十" + (_CN_NUM[rest % 10] if rest % 10 else "")
    return _CN_NUM[h] + "百" + cn(rest)


def _write(folder: str, name: str, content: str) -> None:
    path = DOCS_DIR / folder / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"  ✓ {folder}/{name}（{len(content)} 字）")


