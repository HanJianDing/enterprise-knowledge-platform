def gen_handbook_commentary() -> None:
    """《制度全集逐条解读》：每主题一章，逐条附官方解读段落（机械扩写，
    产出 3 万字级厚文档，供 RAPTOR/TOC 评估）；解读中刻意写入《》引用
    （验收批次1·8h：为文档引用图 pagerank 养数据）"""
    from scripts.gen_demo_themes import (
        ADM_THEMES, EXTRA_THEMES, FIN_THEMES, HR_THEMES, IT_THEMES,
        MKT_THEMES, PUB_THEMES, RD_THEMES,
    )
    groups = [("人事制度", list(HR_THEMES)), ("行政制度", list(ADM_THEMES)),
              ("财务制度", list(FIN_THEMES)), ("IT制度", list(IT_THEMES)),
              ("市场制度", list(MKT_THEMES)), ("研发制度", list(RD_THEMES)),
              ("公共制度", list(PUB_THEMES)),
              ("补充制度", [t for ts in EXTRA_THEMES.values() for t in ts])]
    lines = ["云帆科技制度全集逐条解读", "", "编制说明",
             "本解读由人事部会同各部门编写，对公司现行制度逐条释义，帮助员工准确理解与执行。"
             "解读内容与单行制度不一致的，以最新发布的单行制度为准。", "", "目录"]
    chapter = 1
    toc = []
    for gname, themes in groups:
        for theme in themes:
            name, law, *_ = theme
            if not law:
                continue
            toc.append(f"{cn(chapter)}. 第{cn(chapter)}章 {name}")
            chapter += 1
    lines.extend(toc)
    lines.append("")
    chapter = 1
    for gname, themes in groups:
        for theme in themes:
            name, law, *_ = theme
            if not law:
                continue
            lines.append(f"第{cn(chapter)}章 {name}的制度解读")
            for i, (title, content) in enumerate(law, 1):
                lines.append(f"第{cn(i)}条 {title}")
