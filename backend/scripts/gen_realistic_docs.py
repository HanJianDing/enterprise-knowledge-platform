def _load_font(size: int):
    from PIL import ImageFont
    for path in ("C:/Windows/Fonts/msyh.ttc", "C:/Windows/Fonts/msyh.ttf",
                 "C:/Windows/Fonts/simhei.ttf", "C:/Windows/Fonts/simsun.ttc"):
        try:
            return ImageFont.truetype(path, size)
        except Exception:
            continue
    return ImageFont.load_default()


def _draw_flow(name: str, title: str, steps: list[tuple[str, str]]):
    """画纵向流程图：标题 + 步骤框 + 向下箭头；steps=[(框文字, 备注或None)]"""
    from PIL import Image, ImageDraw

    W, H = 1100, 220 + len(steps) * 150
    img = Image.new("RGB", (W, H), "white")
    draw = ImageDraw.Draw(img)
    font_title = _load_font(40)
    font_box = _load_font(28)
    font_note = _load_font(22)

    draw.text((W // 2, 60), title, font=font_title, fill="#1f2d3d", anchor="mm")
    y = 140
    for i, (text, note) in enumerate(steps):
        x0, x1 = W // 2 - 330, W // 2 + 330
        draw.rounded_rectangle([x0, y, x1, y + 76], radius=12, fill="#1677ff")
        draw.text((W // 2, y + 38), text, font=font_box, fill="white", anchor="mm")
        if note:
            draw.text((W // 2, y + 92), note, font=font_note, fill="#555", anchor="mm")
        if i < len(steps) - 1:
            arrow_y = y + (106 if note else 76)
            draw.polygon(
                [(W // 2 - 10, arrow_y), (W // 2 + 10, arrow_y), (W // 2, arrow_y + 24)],
                fill="#1677ff",
            )
            y = arrow_y + 30
        else:
            y += 110 if note else 80
    img.save(IMG_DIR / name)
    print(f"  ✓ 图片文档/{name}")


