def gen_handbook() -> None:
    """按主题逐章汇编员工手册（第X章=主题，章内第X条=该主题制度条款）"""
    from scripts.gen_demo_themes import (  # 只读 import，写入仅在 main
        ADM_THEMES, EXTRA_THEMES, FIN_THEMES, HR_THEMES, IT_THEMES,
        MKT_THEMES, PUB_THEMES, RD_THEMES,
    )
    groups = [
        ("人事制度", list(HR_THEMES)),
        ("行政制度", list(ADM_THEMES)),
        ("财务制度", list(FIN_THEMES)),
        ("IT 制度", list(IT_THEMES)),
        ("市场制度", list(MKT_THEMES)),
        ("研发制度", list(RD_THEMES)),
        ("公共制度", list(PUB_THEMES)),
        ("补充制度", [t for ts in EXTRA_THEMES.values() for t in ts]),
    ]
    lines = _HANDBOOK_PREAMBLE.strip().split("\n")
    chapter = 2
    for _group_name, themes in groups:
        for theme in themes:
            name, law, *_ = theme
            if not law:
                continue
            lines.append(f"第{cn(chapter)}章 {name}")
            for i, (title, content) in enumerate(law, 1):
                lines.append(f"第{cn(i)}条 {title}")
                lines.append(content)
            lines.append("")
            chapter += 1
    # 附则章号按实际章数动态编号（不依赖写死的占位字符串）
    lines.append(f"第{cn(chapter)}章 附则")
    lines.extend(_HANDBOOK_TAIL.strip().split("\n")[1:])
    _write("人事部", "员工手册.txt", "\n".join(lines))


# ═══════════ 2. 管理制度汇编（拼接制度类文档 + 目录） ═══════════

_ASSEMBLY_KEYWORDS = ("制度", "规范", "办法", "准则", "标准", "规定")


def gen_assembly() -> None:
    folders = ["人事部", "财务部", "行政部", "IT部", "市场部", "研发部", "公共"]
    files: list[Path] = []
    for folder in folders:
        p = DOCS_DIR / folder
        if not p.exists():
            continue
        for f in sorted(p.iterdir()):
            # 排除汇编自身：重跑时把上次生成的汇编拼进自身会逐次膨胀（质检中危修复）
            if f.name == "管理制度汇编.txt":
                continue
            # 批次F 验收修复：排除废止历史版制度（"（2023版）/（2024版）"）——
            # 汇编块会随检索召回，LLM 采信废止条款文本（真实验收："报销
            # 3000"依据被编成《审批权限与流程制度（2024版）》）；汇编只
            # 收现行制度
            if "（20" in f.stem and f.stem.endswith("版）"):
                continue
            if f.suffix.lower() == ".txt" and any(k in f.stem for k in _ASSEMBLY_KEYWORDS):
                files.append(f)
    lines = ["云帆科技管理制度汇编", "", "目录"]
    for i, f in enumerate(files, 1):
        lines.append(f"{i}. {f.stem}")
    lines.append("")
    for f in files:
        content = f.read_text(encoding="utf-8", errors="ignore").strip()
        lines.append(f"## {f.stem}")
        lines.append(content)
        lines.append("")
    _write("公共", "管理制度汇编.txt", "\n".join(lines))


