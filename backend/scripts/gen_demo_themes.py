"""演示文档生成器（批次B）：60 个业务主题 × 4 形态文档 + 2 份年度差旅标准

在 D:\\文档数据 各部门目录生成补充文档（虚构公司"云帆科技"，内容互相自洽）。
与 gen_demo_docs.py 的分工：那个生成核心制度；这个按"主题"批量生成
制度/流程/表单/FAQ 四形态，支撑两层分类树（主题父分类 + 形态子分类）。
生成后运行 scripts/seed_demo.py 重新种子（幂等）。
"""
import csv
from pathlib import Path

DOCS_DIR = Path("D:/文档数据")

# ═══════════ 主题规格：每个主题 4 份文档（制度/流程/表单/FAQ） ═══════════
# (主题名, 制度条款[(标题, 内容)...], 流程步骤[...], 表单(表头, 行), FAQ[(问,答)...])

def write_txt(folder: str, name: str, content: str) -> None:
    (DOCS_DIR / folder).mkdir(parents=True, exist_ok=True)
    (DOCS_DIR / folder / name).write_text(content, encoding="utf-8")


def write_md(folder: str, name: str, content: str) -> None:
    write_txt(folder, name, content)


def write_csv(folder: str, name: str, headers: list, rows: list) -> None:
    (DOCS_DIR / folder).mkdir(parents=True, exist_ok=True)
    with open(DOCS_DIR / folder / name, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(headers)
        w.writerows(rows)


def write_xlsx(folder: str, name: str, sheet: str, headers: list, rows: list) -> None:
    from openpyxl import Workbook

    (DOCS_DIR / folder).mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    ws = wb.active
    ws.title = sheet
    ws.append(headers)
    for r in rows:
        ws.append(r)
    wb.save(str(DOCS_DIR / folder / name))


def build_law(name: str, items: list[tuple[str, str]]) -> str:
    lines = [f"云帆科技{name}"]
    for i, (title, content) in enumerate(items, 1):
        cn = "一二三四五六七八九十"
        num = cn[i - 1] if i <= 10 else str(i)
        lines.append(f"第{num}条 {title}")
        lines.append(content)
    return "\n".join(lines) + "\n"


def build_flow(name: str, steps: list[str]) -> str:
    lines = [f"# 云帆科技{name}", ""]
    for i, s in enumerate(steps, 1):
        lines.append(f"{i}. {s}")
    return "\n".join(lines) + "\n"


def build_faq(name: str, pairs: list[tuple[str, str]]) -> str:
    lines = [f"# {name}常见问题（FAQ）", ""]
    for q, a in pairs:
        lines.append(f"问：{q}")
        lines.append(f"答：{a}")
        lines.append("")
    return "\n".join(lines)


def gen_theme(folder: str, theme: str, law: list, flow: list, form, faq: list, xlsx: bool = False) -> None:
    """按主题生成 4 份文档：制度 txt / 流程 md / 表单 csv|xlsx / FAQ md"""
    write_txt(folder, f"{theme}管理制度.txt", build_law(f"{theme}管理制度", law))
    write_md(folder, f"{theme}操作流程.md", build_flow(f"{theme}操作流程", flow))
    headers, rows = form
    if xlsx:
        write_xlsx(folder, f"{theme}登记表.xlsx", theme, headers, rows)
    else:
        write_csv(folder, f"{theme}登记表.csv", headers, rows)
    write_md(folder, f"{theme}常见问题.md", build_faq(theme, faq))


