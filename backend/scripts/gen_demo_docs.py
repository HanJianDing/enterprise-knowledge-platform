def _inject_citations(name: str, content: str) -> str:
    """语料增强二期·8h：尾部注入"相关制度"引用行（pagerank 养图）。
    幂等：生成器每次全量重写文件（不叠加）；矩阵外文件名原样返回。"""
    cited = _CITATIONS.get(name)
    if not cited:
        return content
    refs = "".join(f"《{c}》" for c in cited)
    return content.rstrip() + f"\n\n相关制度\n本制度涉及的相关规定详见：{refs}。\n"


def write_txt(folder: str, name: str, content: str) -> None:
    content = _inject_citations(name, content)
    (DOCS_DIR / folder).mkdir(parents=True, exist_ok=True)
    (DOCS_DIR / folder / name).write_text(content, encoding="utf-8")


def write_md(folder: str, name: str, content: str) -> None:
    write_txt(folder, name, content)


def write_csv(folder: str, name: str, headers: list, rows: list) -> None:
    (DOCS_DIR / folder).mkdir(parents=True, exist_ok=True)
    with open(DOCS_DIR / folder / name, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(headers)
        writer.writerows(rows)


def write_xlsx(folder: str, name: str, sheet: str, headers: list, rows: list) -> None:
    from openpyxl import Workbook

    (DOCS_DIR / folder).mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    ws = wb.active
    ws.title = sheet
    ws.append(headers)
    for row in rows:
        ws.append(row)
    wb.save(str(DOCS_DIR / folder / name))


def write_docx(folder: str, name: str, title: str, paragraphs: list) -> None:
    from docx import Document as DocxDocument

    (DOCS_DIR / folder).mkdir(parents=True, exist_ok=True)
    doc = DocxDocument()
    doc.add_heading(title, level=0)
    for p in paragraphs:
        doc.add_paragraph(p)
    doc.save(str(DOCS_DIR / folder / name))


